// Copies the FSM product stylesheet and icon set into the docs site, so every
// component demo renders with the real implementation.
//   node scripts/sync-product.mjs [path/to/NPD-FSM]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import vm from "node:vm";

const src = resolve(process.argv[2] ?? "../../Prototype/SMS_FSM/NPD-FSM");

// Stylesheet: demos live in a shadow root, where :root never matches.
const css = readFileSync(`${src}/styles.css`, "utf8").replace(/:root\b/g, ":host");
writeFileSync("public/product/fsm.css", `/* Generated by scripts/sync-product.mjs from NPD-FSM/styles.css. Do not edit. */\n${css}`);

// Icons: the `P` path map that ic(name, size) reads in script.js.
const js = readFileSync(`${src}/script.js`, "utf8");
const start = js.indexOf("const P={");
const end = js.indexOf("\n};", start) + 3;
const P = vm.runInNewContext(`(${js.slice(start + "const P=".length, end - 1)})`);
writeFileSync(
  "components/demo/icons.ts",
  `/* Generated by scripts/sync-product.mjs from NPD-FSM/script.js (the ic() path map). Do not edit. */\n` +
    `export const PATHS: Record<string, string> = ${JSON.stringify(P, null, 2)};\n`,
);
console.log(`styles: ${css.length} chars · icons: ${Object.keys(P).length}`);
